<script>
  function filterGallery(category) {
    const cards = document.querySelectorAll('.gallery-card');
    const buttons = document.querySelectorAll('.gallery-filter-btn');

    buttons.forEach(btn => {
      if (btn.getAttribute('data-filter') === category) {
        btn.classList.add('bg-[#0F2A24]', 'text-white', 'shadow-md');
        btn.classList.remove('bg-white', 'text-stone-700', 'border', 'border-stone-300');
      } else {
        btn.classList.remove('bg-[#0F2A24]', 'text-white', 'shadow-md');
        btn.classList.add('bg-white', 'text-stone-700', 'border', 'border-stone-300');
      }
    });

    cards.forEach(card => {
      const villa = card.getAttribute('data-villa');
      if (category === 'all' || villa === category) {
        card.style.display = 'flex';
      } else {
        card.style.display = 'none';
      }
    });
  }

  function openGalleryModal(src, title, desc) {
    const modal = document.getElementById('gallery-lightbox');
    const img = document.getElementById('lightbox-img');
    const t = document.getElementById('lightbox-title');
    const d = document.getElementById('lightbox-desc');
    if (!modal || !img) return;

    img.src = src;
    t.innerText = title || '';
    d.innerText = desc || '';
    modal.classList.remove('hidden');
    modal.classList.add('flex');
    document.body.style.overflow = 'hidden';
  }

  function closeGalleryModal() {
    const modal = document.getElementById('gallery-lightbox');
    if (!modal) return;
    modal.classList.add('hidden');
    modal.classList.remove('flex');
    document.body.style.overflow = 'auto';
  }

  function toggleFaq(index) {
    const ans = document.getElementById(`faq-ans-${index}`);
    const icon = document.getElementById(`faq-icon-${index}`);
    if (!ans) return;
    const isOpen = !ans.classList.contains('hidden');
    if (isOpen) {
      ans.classList.add('hidden');
      if (icon) icon.style.transform = 'rotate(0deg)';
    } else {
      ans.classList.remove('hidden');
      if (icon) icon.style.transform = 'rotate(180deg)';
    }
  }

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeGalleryModal();
  });
</script>

